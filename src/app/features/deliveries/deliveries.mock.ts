/** Mirrors what the API does with the filters, so the dev session can exercise the UI. */
export function filterMockDeliveries(
  items: DeliverySummary[],
  filters: ParcelFilters,
): DeliverySummary[] {
  const state = filters.state.toLowerCase();
  const city = filters.city.toLowerCase();
  return items.filter((item) => {
    const day = item.createdAt?.slice(0, 10) ?? '';
    const address = (item.dropOff ?? '').toLowerCase();
    return (
      (!filters.dateFrom || (day !== '' && day >= filters.dateFrom)) &&
      (!filters.dateTo || (day !== '' && day <= filters.dateTo)) &&
      (filters.minPrice === null || (item.amount ?? 0) >= filters.minPrice) &&
      (filters.maxPrice === null || (item.amount ?? 0) <= filters.maxPrice) &&
      (!state || address.includes(state)) &&
      (!city || address.includes(city))
    );
  });
}
